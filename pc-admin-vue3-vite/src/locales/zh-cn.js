export function tx(key, params) {
  if (key == null) return ''
  let str = zhCN[key]
  if (str == null) str = key
  if (params && typeof str === 'string') {
    str = str.replace(/\{(\w+)\}/g, (_, name) =>
      params[name] != null ? String(params[name]) : `{${name}}`
    )
  }
  return str
}
